export function java17Download(platform: string, arch: string) {
  const os = ({ win32: 'windows', darwin: 'macOS', linux: 'linux' } as Record<string, string>)[
    platform
  ];
  const cpu = ({ x64: 'x64', arm64: 'aarch64' } as Record<string, string>)[arch];
  if (!os || !cpu)
    throw new Error(`Automatic Java 17 download is unavailable for ${platform}/${arch}.`);
  const extension = platform === 'win32' ? 'zip' : 'tar.gz';
  const url = `https://aka.ms/download-jdk/microsoft-jdk-17-${os}-${cpu}.${extension}`;
  return { url, checksum: url + '.sha256sum.txt', extension };
}
const run = (file: string, args: string[]) =>
  new Promise<string>((resolve, reject) => {
    execFile(
      file,
      args,
      { windowsHide: true, timeout: 120_000, maxBuffer: 4 * 1024 * 1024 },
      (error, stdout) => (error ? reject(error) : resolve(stdout)),
    );
  });
export function archiveRoot(list: string) {
  const entries = list.trim().split(/\r?\n/).filter(Boolean);
  if (
    !entries.length ||
    entries.some((entry) => /[\\:\0]|^\//.test(entry) || entry.split('/').includes('..'))
  )
    throw new Error('Unsafe Java archive paths.');
  const roots = new Set(entries.map((entry) => entry.split('/')[0]));
  if (roots.size !== 1) throw new Error('Expected one Java archive root.');
  return [...roots][0];
}
export async function downloadJava17(
  stage: string,
  platform: string,
  arch: string,
  request: typeof fetch = fetch,
) {
  const spec = java17Download(platform, arch);
  const signal = AbortSignal.timeout(300_000);
  const checksum = await request(spec.checksum, { signal });
  if (!checksum.ok || (checksum.url && !checksum.url.startsWith('https://')))
    throw new Error(`Java checksum download failed (${checksum.status}).`);
  const expected = /^([a-f\d]{64})(?:\s|$)/i
    .exec((await checksum.text()).trim())?.[1]
    .toLowerCase();
  if (!expected) throw new Error('Java download checksum is invalid.');
  const response = await request(spec.url, { signal });
  if (!response.ok || !response.body || (response.url && !response.url.startsWith('https://')))
    throw new Error(`Java archive download failed (${response.status}).`);
  let bytes = 0;
  const digest = createHash('sha256');
  const archive = path.join(stage, 'java.' + spec.extension);
  await pipeline(
    Readable.fromWeb(response.body as never),
    new Transform({
      transform(chunk, _encoding, done) {
        bytes += chunk.length;
        if (bytes > 350 * 1024 * 1024)
          return done(new Error('Java download exceeds the size limit.'));
        digest.update(chunk);
        done(null, chunk);
      },
    }),
    createWriteStream(archive),
    { signal },
  );
  if (digest.digest('hex') !== expected)
    throw new Error('Java archive checksum mismatch; nothing was installed.');
  const root = archiveRoot(await run('tar', ['-tf', archive]));
  await run('tar', ['-xf', archive, '-C', stage]);
  return path.join(stage, root);
}
const propertyMarker = '# WatDatMean managed build JVM (regenerated by npm ci)';
// NetBeans identifies a registered project JDK by its canonical path, converted to
// an Ant property name (PropertyUtils.getUsablePropertyName). Resolve links first:
// npm setup may reuse an installed JDK through a junction/symlink.
export function oraclePlatformId(canonicalHome: string) {
  return canonicalHome.replace(/[^a-zA-Z0-9_.-]/g, '_');
}
export function configureBuildProperties(text: string, home: string, oracleId?: string) {
  const oracleMarker =
    /# WatDatMean managed Oracle Gradle runtime\r?\nnetbeans\.hint\.jdkPlatform=[^\r\n]*(?:\r?\n)?/g;
  const withoutManaged = (oracleId ? text.replace(oracleMarker, '') : text).replace(
    /# WatDatMean managed build JVM \(regenerated by npm ci\)\r?\norg\.gradle\.java\.home=[^\r\n]*(?:\r?\n)?/g,
    '',
  );
  // Keep an explicit developer override and every unrelated Gradle property.
  if (/^\s*org\.gradle\.java\.home\s*[:=]/m.test(withoutManaged)) return text;
  const escaped = home
    .replaceAll('\\', '/')
    .replaceAll(':', '\\:')
    .replace(
      /[^\x20-\x7e]/g,
      (character) => '\\u' + character.charCodeAt(0).toString(16).padStart(4, '0'),
    );
  let result =
    withoutManaged.trimEnd() +
    (withoutManaged.trim() ? '\n\n' : '') +
    `${propertyMarker}\norg.gradle.java.home=${escaped}\n`;
  if (oracleId) {
    if (!/^\s*netbeans\.hint\.jdkPlatform\s*[:=]/m.test(result))
      result += `# WatDatMean managed Oracle Gradle runtime\nnetbeans.hint.jdkPlatform=${oracleId}\n`;
  }
  return result;
}
export async function setupBuildJava(
  root: string,
  options: {
    host?: JavaRuntimeHost;
    arch?: string;
    download?: typeof downloadJava17;
    log?: (message: string) => void;
  } = {},
) {
  const host = options.host ?? javaRuntimeHost;
  const log = options.log ?? console.log;
  const base = path.resolve(root, 'intellij/.gradle');
  const home = path.join(base, 'java-home');
  const valid = async (location: string) => {
    const java = await inspectJava(location, host);
    return java?.major === 17 && !java.earlyAccess && (await host.probe(java.executable, []))
      ? java
      : undefined;
  };
  await mkdir(base, { recursive: true });
  let java = await valid(home);
  if (!java) {
    const plan = await planJavaRuntime({ minimum: 17, maximum: 17, flags: [] }, host);
    const found =
      plan.status === 'healthy'
        ? plan.current
        : plan.status === 'repair'
          ? plan.selected
          : undefined;
    const stage = await mkdtemp(path.join(base, 'java-setup-'));
    try {
      let staged = path.join(stage, 'home');
      if (found && !found.earlyAccess) {
        log('WatDatMean: reusing installed Java 17 for the IntelliJ build.');
        try {
          await symlink(found.home, staged, host.platform === 'win32' ? 'junction' : 'dir');
        } catch (error) {
          if (!['EPERM', 'EACCES', 'ENOSYS'].includes((error as NodeJS.ErrnoException).code ?? ''))
            throw error;
          // Restricted Windows accounts may forbid links; a private copy needs no admin rights.
          await cp(found.home, staged, { recursive: true });
        }
      } else {
        log('WatDatMean: downloading and verifying a private Java 17 build runtime.');
        const unpacked = await (options.download ?? downloadJava17)(
          stage,
          host.platform,
          options.arch ?? process.arch,
        );
        const installed = await valid(unpacked);
        if (!installed) throw new Error('Downloaded Java runtime did not pass the Java 17 check.');
        // macOS archives contain Contents/Home. Move the actual JDK, not the enclosing bundle.
        staged = installed.home;
      }
      // Preserve a stale installation instead of deleting it. A concurrent successful setup wins.
      java = await valid(home);
      if (!java) {
        await rename(home, path.join(base, 'java-previous-' + randomUUID())).catch((error) => {
          if (error.code !== 'ENOENT') throw error;
        });
        try {
          await rename(staged, home);
        } catch (error) {
          if (!(await valid(home))) throw error;
        }
      }
      java = await valid(home);
      if (!java) throw new Error('The Java 17 build runtime could not be started.');
    } finally {
      // Only the unique staging directory created above is removed; never an installed JDK.
      if (!stage.startsWith(base + path.sep)) throw new Error('Invalid Java staging path');
      await rm(stage, { recursive: true, force: true });
    }
  }
  const file = path.resolve(root, 'intellij/gradle.properties');
  const previous = await readFile(file, 'utf8').catch((error) => {
    if (error.code !== 'ENOENT') throw error;
    return '';
  });
  const next = configureBuildProperties(previous, home, oraclePlatformId(await realpath(home)));
  if (previous !== next) {
    const temporary = file + '.' + randomUUID() + '.tmp';
    await writeFile(temporary, next);
    await rename(temporary, file);
  }
  const settingsFile = path.join(root, '.vscode/settings.json');
  const stateFile = path.join(base, 'editor-java-home.json');
  const readOptional = (name: string) =>
    readFile(name, 'utf8').catch((error) => {
      if (error.code !== 'ENOENT') throw error;
      return '';
    });
  const editorHome = home.replaceAll('\\', '/');
  const savedHome = await readOptional(stateFile);
  const previousHome: unknown = savedHome ? JSON.parse(savedHome) : undefined;
  const settingsBefore = await readOptional(settingsFile);
  const settingsAfter = configureBuildEditorSettings(
    settingsBefore,
    editorHome,
    typeof previousHome === 'string' ? previousHome : undefined,
  );
  if (settingsAfter !== settingsBefore) {
    await mkdir(path.dirname(settingsFile), { recursive: true });
    const temporary = settingsFile + '.' + randomUUID() + '.tmp';
    await writeFile(temporary, settingsAfter);
    await rename(temporary, settingsFile);
  }
  if (previousHome !== editorHome) await writeFile(stateFile, JSON.stringify(editorHome) + '\n');
  log('WatDatMean: Java 17 ready; the IntelliJ build uses the pinned Gradle wrapper.');
  return home;
}
