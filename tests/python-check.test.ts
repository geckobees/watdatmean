import { describe, expect, it } from 'vitest';
import { checkSyntax } from '../src/languages';

describe('Python preview checks beyond the recovering editor grammar', () => {
  it.each([
    ['missing body indentation', 'if True:\nprint(1)'],
    ['unmatched dedent', 'if True:\n    x=1\n  y=2'],
    ['extra module indentation', 'x=1\n    y=2'],
    ['indented first line', '    x=1'],
    ['ambiguous tabs and spaces', 'if True:\n\tx=1\n        y=2'],
    ['wrong else indentation', 'if True:\n    x=1\n  else:\n    x=2'],
    ['return outside a function', 'return 3'],
    ['return in a class body', 'def f():\n class C:\n  return 3'],
    ['break outside a loop', 'break'],
    ['continue outside a loop', 'continue'],
    ['break in a nested function', 'for x in [1]:\n def f():\n  break'],
    ['break in loop else', 'for x in [1]:\n pass\nelse:\n break'],
    ['yield outside a function', 'yield 3'],
    ['await outside async', 'await f()'],
    ['await inside a sync function', 'def f():\n await g()'],
    ['async loop outside a function', 'async for x in stream:\n print(x)'],
    ['nonlocal at module scope', 'nonlocal value'],
    ['duplicate parameters', 'def f(value, value):\n return value'],
    ['required after default', 'def f(value=1, other):\n return value'],
    ['parameter after kwargs', 'def f(**kwargs, value):\n return value'],
    ['assignment to a number', '1 = value'],
    ['assignment to a call', 'f() = 3'],
    ['assignment to a calculation', 'a + b = 3'],
    ['bad nested unpacking target', 'a, [b, 2] = values'],
    ['two starred unpacking targets', 'a, *b, *c = values'],
    ['bare starred target', '*a = values'],
    ['tuple augmented assignment', 'a, b += values'],
    ['annotated tuple assignment', 'a, b: int = values'],
    ['assignment to __debug__', '__debug__ = True'],
    ['delete literal', 'del 3'],
    ['for literal target', 'for 3 in values:\n pass'],
    ['walrus attribute target', 'if (item.value := 3):\n pass'],
    ['leading-zero integer', 'value = 02'],
    ['try without handler', 'try:\n value=1'],
    ['try else without except', 'try:\n value=1\nelse:\n value=2\nfinally:\n pass'],
    [
      'bare except before another handler',
      'try:\n pass\nexcept:\n pass\nexcept ValueError:\n pass',
    ],
    ['Python 2 print', 'print "hello"'],
    ['unclosed quoted string', 'value = "hello'],
    ['unclosed triple string', 'value = """hello'],
    ['unfinished function', 'def total(prices):\n return sum('],
    ['missing body', 'def f():'],
    ['null character', 'value = "\0"'],
  ])('blocks %s', (_name, code) => {
    const result = checkSyntax(code, 'python');
    expect(result.checked).toBe(true);
    expect(result.errors.length, code).toBeGreaterThan(0);
    expect(result.errors.length).toBeLessThanOrEqual(8);
  });

  it.each([
    ['empty file', ''],
    ['comment', '# if True:\n#   return 3'],
    ['receipt', 'prices = [2, 3, 4]\ntotal = sum(prices)\nprint(total)'],
    ['alias and call', 'import math as m\nprint(m.sqrt(9))'],
    ['consistent spaces', 'if True:\n    x=1\n    y=2\nz=3'],
    ['consistent tabs', 'if True:\n\tx=1\n\ty=2'],
    [
      'nested blocks and dedent',
      'if True:\n    for x in [1]:\n        print(x)\n    print("done")',
    ],
    ['else branch', 'if True:\n x=1\nelse:\n x=2'],
    ['inline suite', 'if True: x=1; y=2'],
    ['semicolon statements', 'x=1; y=2'],
    ['multiline list', 'values = [\n  1,\n  2\n]'],
    ['multiline condition', 'if (\n True\n):\n print(1)'],
    ['explicit continuation', 'value = 1 + \\\n 2'],
    ['triple quoted contents', 'message = """hello\n  return 3\n    world"""'],
    ['formatted string', 'name = "Ada"\nmessage = f"Hello {name}"'],
    ['Unicode and CRLF', 'π = 3\r\nprint("😀", π)'],
    ['CR line endings', 'if True:\r    print(1)\rprint(2)'],
    ['function', 'def total(prices):\n return sum(prices)'],
    ['method', 'class C:\n def run(self):\n  return 3'],
    ['decorator', '@decorator\ndef run():\n return 3'],
    ['nested decorators', 'class C:\n @staticmethod\n def run():\n  return 3'],
    ['lambda', 'double = lambda x: x * 2'],
    ['default values', 'def f(x, y=1):\n return x+y'],
    ['keyword-only argument', 'def f(x=1, *, y):\n return x+y'],
    ['positional-only arguments', 'def f(x, /, y=1, *args, z, **kwargs):\n return x'],
    ['outer nonlocal', 'def outer():\n value=1\n def inner():\n  nonlocal value\n  value=2'],
    ['valid loop jumps', 'for x in [1,2]:\n if x==1:\n  continue\n break'],
    ['outer loop from inner else', 'while True:\n for x in []:\n  pass\n else:\n  break'],
    ['async function', 'async def run():\n result = await work()\n return result'],
    ['async loop', 'async def run():\n async for item in stream:\n  print(item)'],
    ['generator', 'def values():\n yield 3'],
    ['generator lambda', 'value = lambda: (yield 1)'],
    ['unpacking', 'a, (b, c) = values'],
    ['starred list unpacking', '[*items] = values'],
    ['starred tuple unpacking', 'first, *rest = values'],
    ['chained assignment', 'a = b = 3'],
    ['typed assignment', 'value: int = 3'],
    ['member assignments', 'obj.value = 3\nitems[0] += 1'],
    ['delete target', 'del obj.value, items[0]'],
    ['zero and other numeric forms', 'zero=00\nhexadecimal=0xFF\ndecimal=02.5\nscientific=02e2'],
    ['try finally', 'try:\n work()\nfinally:\n close()'],
    [
      'try except else finally',
      'try:\n work()\nexcept ValueError:\n handle()\nelse:\n done()\nfinally:\n close()',
    ],
    ['match', 'match value:\n case 1:\n  print("one")\n case _:\n  print("other")'],
    ['comprehension', 'squares = [n*n for n in range(4) if n>0]'],
    ['resource context', 'with open("data.txt") as file:\n text = file.read()'],
  ])('accepts %s without running it', (_name, code) => {
    expect(checkSyntax(code, 'python'), code).toEqual({ checked: true, errors: [] });
  });
});
